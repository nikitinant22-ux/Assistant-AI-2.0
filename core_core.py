def send_cad_prompt(message: str) -> None:
    """Выводит текстовое уведомление робота в командную строку AutoCAD.

    Все сообщения ассистента на экране начинаются с префикса [AI-Ассистент]: .
    Функция использует doc.Utility.Prompt() — это безопасный способ показать
    текст пользователю без запуска команд и без вмешательства в чертёж.

    Аргументы:
        message: текст уведомления (строка). Дополняется префиксом автоматически.

    Исключения не выбрасываются наружу: при сбое соединения сообщение
    выводится в консоль Python, чтобы не нарушать работу других агентов.
    """
    global doc
    if doc is None:
        print(f"{AI_PREFIX}Соединение с AutoCAD не установлено, сообщение: {message}")
        return
    try:
        doc.Utility.Prompt(f"{AI_PREFIX}{message}\n")
    except Exception as exc:
        print(f"{AI_PREFIX}Не удалось вывести сообщение в AutoCAD: {exc}")


def update_screen() -> None:
    """Принудительно обновляет графический экран AutoCAD.

    Вызывает doc.Update(), благодаря чему пользователь сразу видит изменения,
    внесённые Чертёжником или Оператором, не дожидаясь ручного регена.

    Исключения не выбрасываются наружу: при отсутствии соединения выполняет
    «мягкое» игнорирование и записывает предупреждение в консоль Python.
    """
    global doc
    if doc is None:
        print("[core_core] Автообновление экрана пропущено: нет соединения с AutoCAD.")
        return
    try:
        doc.Update()
    except Exception as exc:
        print(f"[core_core] Не удалось обновить экран AutoCAD: {exc}")


