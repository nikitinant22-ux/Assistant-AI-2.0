# Функция для «ленивого» получения актуального соединения (без передачи аргументов).
def ensure_connection():
    """Гарантирует установленное соединение и возвращает кортеж COM-объектов.

    Является удобной обёрткой над get_autocad_connection() и предназначена для
    случаев, когда агенту нужны актуальные ссылки acad_app, doc, model_space
    одной строкой.

    Возвращает:
        tuple (acad_app, doc, model_space).
    """
    return get_autocad_connection()


