def get_autocad_connection():
    """Устанавливает и возвращает соединение с активным экземпляром AutoCAD.

    Стратегия подключения двухступенчатая:
        1. Сначала пытается перехватить уже запущенное окно программы через
           win32com.client.GetActiveObject("AutoCAD.Application"). Это самый
           быстрый и безопасный способ — он не запускает новый процесс.
        2. Если это не удалось (AutoCAD закрыт, занят модальным окном или
           недоступен), выполняется резервный win32com.client.Dispatch, а при
           его неудаче пользователю возвращается понятное сообщение на русском.

    После успешного соединения заполняются глобальные переменные acad_app,
    doc и model_space, а также устанавливается флаг _connected. Повторные
    вызовы функции не пересоздают объект, если соединение уже установлено.

    Возвращает:
        tuple (acad_app, doc, model_space) — кортеж COM-объектов при успехе.

    Выбрасывает:
        RuntimeError — если подключение не удалось (с пояснением на русском).
    """
    global acad_app, doc, model_space, _connected

    # Если соединение уже установлено — просто возвращаем сохранённые ссылки.
    if _connected and acad_app is not None and doc is not None:
        return acad_app, doc, model_space

    if win32com is None:
        raise RuntimeError(
            "Не удалось импортировать библиотеку pywin32. "
            "Установите её: pip install pywin32. " + CONNECTION_ERROR_MESSAGE
        )

    # --- Шаг 1: пытаемся перехватить активное запущенное окно AutoCAD ---------
    try:
        acad_app = win32com.client.GetActiveObject(AUTOCAD_PROG_ID)
    except Exception as exc:
        # Запоминаем детали первой ошибки для резервного сообщения.
        first_error = _describe_com_error(exc)
        # --- Шаг 2: резервный вариант — Dispatch (создание/подключение) --------
        try:
            acad_app = win32com.client.Dispatch(AUTOCAD_PROG_ID)
        except Exception as fallback_exc:
            second_error = _describe_com_error(fallback_exc)
            raise RuntimeError(
                f"{CONNECTION_ERROR_MESSAGE}\n"
                f"(Подробности: {first_error}; {second_error})"
            )

    # --- Заполняем ссылки на документ и пространство модели ------------------
    try:
        doc = acad_app.ActiveDocument
        model_space = doc.ModelSpace
    except Exception as exc:
        raise RuntimeError(
            "Подключение к AutoCAD установлено, но не удалось получить "
            f"активный документ и пространство модели. {_describe_com_error(exc)}"
        )

    _connected = True
    return acad_app, doc, model_space


def _describe_com_error(exc: Exception) -> str:
    """Формирует краткое человекочитаемое описание COM-ошибки.

    Специально обрабатывает характерный признак «занятости» AutoCAD
    (код -2147418111 / сообщение "Busy"), чтобы дать пользователю корректную
    подсказку: программа работает с модальным окном и не может ответить.

    Аргументы:
        exc: пойманное исключение (обычно pywintypes.com_error или Exception).

    Возвращает:
        str — строка описания ошибки, пригодная для показа пользователю.
    """
    text = str(exc)
    low = text.lower()
    if "-2147418111" in text or "busy" in low or "занят" in low:
        return "AutoCAD занят (возможно, открыто модальное окно). Закройте его и повторите."
    if text.strip():
        return text
    return "неизвестная ошибка COM."


