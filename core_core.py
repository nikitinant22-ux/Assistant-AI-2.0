def to_cad_point(x: float, y: float, z: float = 0.0) -> "array.array":
    """Преобразует координаты точки в безопасный COM-массив double.

    AutoCAD ActiveX крайне требователен к типам данных: любые координаты,
    передаваемые в его методы, должны быть упакованы в массив значений типа
    double. Данная функция принудительно приводит входные значения к float и
    возвращает готовый array.array('d', [x, y, z]) — это избавляет остальных
    агентов от ошибок, связанных с целыми числами, строками или списками.

    Аргументы:
        x: координата по оси X (любой числовой тип).
        y: координата по оси Y (любой числовой тип).
        z: координата по оси Z (по умолчанию 0.0, т.к. большинство задач в 2D).

    Возвращает:
        array.array — трёхэлементный массив double, готовый для передачи в COM.

    Пример:
        >>> to_cad_point(10, 20)
        array('d', [10.0, 20.0, 0.0])
    """
    return array.array("d", [float(x), float(y), float(z)])


