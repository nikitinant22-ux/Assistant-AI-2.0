"""core_core.py — Единый фундамент подключения к AutoCAD 2025/2026 через Python.

Данный модуль является общей точкой входа для всех ИИ-агентов (Чертёжник,
Аналитик, Оператор). Он отвечает за:

    1. Безопасное подключение к запущенному экземпляру AutoCAD (GetActiveObject)
       с корректным отказоустойчивым резервным вариантом (Dispatch).
    2. Конвертацию координат в безопасные для COM типы (array.array('d', ...)),
       что защищает остальные модули от «багов типов данных» в AutoCAD ActiveX.
    3. Вывод текстовых уведомлений робота напрямую в командную строку чертежа
       и принудительное обновление графического экрана.

Ссылки на Application, ActiveDocument и ModelSpace вынесены в глобальные
переменные модуля, чтобы другие файлы могли импортировать их одной строкой:

    from core_core import model_space, doc, to_cad_point

Внимание: внутри модуля НЕ используется exec()/eval() — только статичные
функции. Все комментарии и документация написаны строго на русском языке.
"""

