try:
    import win32com.client  # pywin32: клиентский доступ к COM/ActiveX AutoCAD
    import pythoncom
    import pywintypes
except ImportError:  # pragma: no cover - резервный путь для сред без pywin32
    win32com = None
    pythoncom = None
    pywintypes = None

# ---------------------------------------------------------------------------
# Константы модуля
# ---------------------------------------------------------------------------

# Программный идентификатор (ProgID) приложения AutoCAD для COM-подключения.
AUTOCAD_PROG_ID = "AutoCAD.Application"

# Префикс всех сообщений робота, выводимых в командную строку AutoCAD.
AI_PREFIX = "[AI-Ассистент]: "

# Текст понятной пользователю ошибки при невозможности подключиться к САПР.
CONNECTION_ERROR_MESSAGE = (
    "Убедитесь, что AutoCAD запущен и командная строка свободна."
)

# Глобальные ссылки на COM-объекты AutoCAD. Инициализируются лениво при первом
# обращении через get_autocad_connection(). Могут быть переопределены извне.
acad_app = None   # Объект Application (win32com.client.CDispatch)
doc = None        # Активный документ (ActiveDocument / Document)
model_space = None  # Пространство модели текущего чертежа (ModelSpace)
_connected = False  # Флаг успешного установления соединения.


