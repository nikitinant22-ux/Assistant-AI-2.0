def _ensure_connection():
    """Гарантирует актуальное подключение к AutoCAD.

    Вызывает get_autocad_connection() из core_core, который заполняет
    глобальные переменные acad_app, doc и model_space. Если AutoCAD не запущен —
    глобальные ссылки остаются прежними (или None), а функция возвращает False.

    Возвращает:
        bool — True, если соединение с AutoCAD установлено и model_space доступен.
    """
    global model_space, doc
    try:
        acad_app, current_doc, ms = get_autocad_connection()
        doc = current_doc
        model_space = ms
        return model_space is not None
    except Exception:
        return False


def _ok(handle, message):
    """Формирует словарь успешного результата операции построения.

    Аргументы:
        handle: строковый дескриптор (Handle) созданного объекта.
        message: текстовое описание результата на русском языке.

    Возвращает:
        dict — JSON-совместимый словарь со статусом «success».
    """
    return {"status": "success", "handle": str(handle), "message": message}


def _err(message):
    """Формирует словарь ошибки операции построения.

    Аргументы:
        message: текстовое описание ошибки на русском языке.

    Возвращает:
        dict — JSON-совместимый словарь со статусом «error».
    """
    return {"status": "error", "message": message}


