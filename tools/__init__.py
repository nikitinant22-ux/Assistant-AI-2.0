# -*- coding: utf-8 -*-
"""tools — ПАКЕТ ПАКЕТОВ атомарных кубиков САПР (Этап 6, Шаг 1).

Монолитный файл tools_core.py ПОЛНОСТЬЮ ЛИКВИДИРОВАН. Проект переходит на
сверхнадёжную изолированную структуру: ОДИН КУБИК — ОДИН НЕЗАВИСИМЫЙ ФАЙЛ.
Имена подпапок и имена файлов кубиков могут быть абсолютно любыми — система
сама находит и импортирует их автоматически при старте.

При импорте этого пакета выполняется АВТОСКАНЕР:
    1. рекурсивно обходит ВСЕ подпапки внутри tools/ (pkgutil.walk_packages);
    2. принудительно импортирует каждый найденный .py-модуль кубика;
    3. декораторы @register_cad_tool(name) срабатывают автоматически и
       наполняют глобальный реестр tool_registry.CAD_TOOL_REGISTRY.

Именно поэтому во всей системе существует ЕДИНЫЙ сквозной импорт: import tools.
"""

import importlib
import logging
import pkgutil

# Общий служебный слой (мост связи с AutoCAD) реэкспортируется наверх пакета,
# чтобы клиентский код пользовался единым импортом import tools и обращался
# к мосту как tools.ensure_connection() — как раньше к tools_core.ensure_connection().
from tools._shared import ensure_connection  # noqa: F401

# Скрытый лог автосканера: проблемы загрузки отдельного кубика не роняют всё
# приложение (Пока-ёкэ) — битый кубик просто не попадёт в глобальный реестр.
_SCANNER_LOGGER = logging.getLogger("assistant_ai.tools_scanner")

# Модули, имена которых начинаются с "_", считаются служебными (например
# _shared.py) и в сканирование не включаются — это не кубики.
_SERVICE_PREFIX: str = "_"


def _scan_tools_package() -> list:
    """Рекурсивно обходит пакет tools и импортирует все модули кубиков.

    Автосканер не знает заранее ни имён подпапок, ни имён файлов: он
    полагается исключительно на pkgutil.walk_packages, который обходит
    дерево пакета рекурсивно. Каждый найденный модуль принудительно
    загружается через importlib.import_module — этого достаточно, чтобы
    декораторы @register_cad_tool сработали и зарегистрировали кубики.

    Возвращает:
        list — имена успешно импортированных модулей (для диагностики).
    """
    imported_modules: list = []
    # prefix добавляет полное квалифицированное имя (tools.base_geometry.…),
    # поэтому import_module загружает модули по правильным путям без циклов.
    for module_info in pkgutil.walk_packages(__path__, prefix=__name__ + "."):
        module_name: str = module_info.name
        # Служебные модули (последний сегмент имени начинается с "_")
        # пропускаем — они не содержат кубиков.
        last_segment: str = module_name.rsplit(".", 1)[-1]
        if last_segment.startswith(_SERVICE_PREFIX):
            continue
        try:
            # Принудительная загрузка модуля кубика в память.
            importlib.import_module(module_name)
            imported_modules.append(module_name)
        except Exception as exc:
            # Сбой импорта одного кубика не роняет старт приложения (Пока-ёкэ).
            _SCANNER_LOGGER.error(
                "Не удалось импортировать кубик '%s': %s", module_name, exc
            )
    return imported_modules


# Запускаем автосканер сразу при импорте пакета (стартовая инициализация).
# Итоговый список импортированных модулей сохраняется для диагностики.
_SCANNED_MODULES: list = _scan_tools_package()