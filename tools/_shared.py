# -*- coding: utf-8 -*-
"""_shared.py — Служебный модуль ПАКЕТА ПАКЕТОВ tools (общие хелперы кубиков).

Здесь живёт инфраструктура, общая для ВСЕХ атомарных кубиков:
    - импорт библиотеки pyautocad (Autocad, APoint) со штатным fallback
      на локальную копию проекта;
    - защищённый глобальный мост связи с AutoCAD (ensure_connection);
    - строитель JSON-ответа об ошибке (build_error, принцип Пока-ёкэ).

Модуль начинается с "_" и потому НЕ считается кубиком: автосканер пакета
tools (см. tools/__init__.py) пропускает его. Здесь нет ни одного декоратора
@register_cad_tool — только общий служебный слой, который разделяют все
изолированные файлы кубиков.
"""

import json
import sys
import time
from pathlib import Path
from typing import Optional

# ---------------------------------------------------------------------------
# Импорт pyautocad: сначала пробуем штатную установку в окружение,
# при неудаче подключаем локальную копию библиотеки из папки проекта.
# ---------------------------------------------------------------------------
try:
    from pyautocad import Autocad, APoint
except ImportError:
    # Файл лежит в tools/_shared.py, поэтому корень проекта — parent.parent.
    _LOCAL_PYAUTOCAD_PATH = (
        Path(__file__).resolve().parent.parent / "_pyautocad" / "pyautocad-master"
    )
    if _LOCAL_PYAUTOCAD_PATH.is_dir():
        # Добавляем локальный каталог в начало sys.path, чтобы импорт
        # гарантированно взял именно проектную копию библиотеки.
        sys.path.insert(0, str(_LOCAL_PYAUTOCAD_PATH))
        from pyautocad import Autocad, APoint
    else:
        # Локальной копии тоже нет — честно сообщаем о проблеме окружения.
        raise ImportError(
            "Библиотека pyautocad не найдена ни в окружении, ни в папке "
            "'_pyautocad/pyautocad-master'. Установите её или восстановите проект."
        )


# ---------------------------------------------------------------------------
# Глобальное состояние защищённого моста.
# ---------------------------------------------------------------------------

# Единственный живой инстанс Autocad во всей системе (глобальный мост).
_acad_instance: Optional[Autocad] = None

# Количество попыток мягкого повторного подключения при потере COM-указателя.
_RECONNECT_ATTEMPTS: int = 3

# Пауза между попытками повторного подключения (в секундах).
_RECONNECT_DELAY_SEC: float = 1.0


# ---------------------------------------------------------------------------
# Помощник: строитель JSON-ответа об ошибке (Пока-ёкэ).
# ---------------------------------------------------------------------------
def build_error(message: str) -> str:
    """Строит строго валидный JSON-ответ об ошибке кубика.

    Аргументы:
        message: Человекочитаемое описание ошибки на русском языке.

    Возвращает:
        Текстовую JSON-строку вида {"status": "error", "message": "..."}.
    """
    return json.dumps({"status": "error", "message": message}, ensure_ascii=False)


# ---------------------------------------------------------------------------
# Помощник: проверка жизнеспособности COM-указателя.
# ---------------------------------------------------------------------------
def _is_alive(acad: Autocad) -> bool:
    """Проверяет жизнеспособность COM-указателя AutoCAD.

    При потере связи (перезапуск САПР, зависание COM-сервера) любое обращение
    к объекту бросает исключение, которое здесь перехватывается. Эта функция —
    «сторож» моста: если она вернула False, инстанс считается мёртвым и
    подлежит полному пересозданию.

    Аргументы:
        acad: Проверяемый инстанс Autocad.

    Возвращает:
        True, если соединение живо, иначе False.
    """
    try:
        # Контрольная операция: чтение имени активного документа.
        _ = acad.ActiveDocument.Name
        return True
    except Exception:
        return False


# ---------------------------------------------------------------------------
# ГЛАВНЫЙ МОСТ: защищённое подключение к AutoCAD.
# ---------------------------------------------------------------------------
def ensure_connection() -> Optional[Autocad]:
    """Отказоустойчивый глобальный мост связи с AutoCAD.

    Функция возвращает активный живой инстанс Autocad, созданный строго
    через `Autocad(create_if_not_exists=False)` — новый процесс САПР
    принудительно НЕ запускается, если AutoCAD не открыт.

    Логика работы:
      1. Если мост уже поднят — проверяется его жизнеспособность
         контрольной операцией; живой инстанс возвращается сразу.
      2. Если COM-указатель потерян или AutoCAD был перезапущен —
         выполняется мягкое повторное подключение с несколькими попытками
         и короткой паузой между ними.
      3. При исчерпании попыток возвращается None — вызывающий код
         обязан обработать этот случай (например, вернуть JSON-ошибку).

    Возвращает:
        Живой инстанс Autocad для выполнения операций либо None,
        если связь с САПР установить не удалось.
    """
    global _acad_instance

    # 1) Мост уже поднят и жив — отдаём его без лишних действий.
    if _acad_instance is not None and _is_alive(_acad_instance):
        return _acad_instance

    # 2) Мост мёртв или ещё не создан — сбрасываем и подключаемся заново.
    _acad_instance = None
    for attempt in range(1, _RECONNECT_ATTEMPTS + 1):
        try:
            candidate = Autocad(create_if_not_exists=False)
            # Контрольная операция: убеждаемся, что COM-сервер реально отвечает.
            _ = candidate.ActiveDocument
            _acad_instance = candidate
            return _acad_instance
        except Exception:
            # Мягкая пауза перед следующей попыткой — не блокируем систему.
            if attempt < _RECONNECT_ATTEMPTS:
                time.sleep(_RECONNECT_DELAY_SEC)

    # 3) Все попытки исчерпаны — возвращаем None.
    return None