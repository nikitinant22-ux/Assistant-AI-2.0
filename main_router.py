# Роль «Диспетчера DeepSeek» на этапе заглушки выполняет детектор намерений.
# Он имитирует анализ пустого ядра кубиков и перенаправляет команду Справочнику.
_DETECT_RE = re.compile(
    r"(?<!\w)(" + "|".join(re.escape(v) for v in ACTION_VERBS) + r")(?!\w)",
    re.IGNORECASE,
)


def detect_action_verb(text: str) -> Optional[str]:
    """Возвращает первый найденный в тексте глагол действия либо None.

    Аргументы:
        text: текст запроса пользователя.

    Возвращает:
        str | None — найденный глагол-повелитель, либо None, если действий нет.
    """
    match = _DETECT_RE.search(text or "")
    return match.group(1) if match else None


