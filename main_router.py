"""main_router.py — Единая точка входа логики ИИ-суждений (Канон 11.1, 11.2).

Данный модуль — финальный управляющий слой всей системы. Он принимает текстовый
запрос пользователя из UI, определяет намерение и возвращает маршрут исполнения.
На этом этапе база атомарных кубиков pyautocad пуста, поэтому роутер работает в
режиме интеллектуальной заглушки и подготавливает архитектуру под Function Calling.

Основные обязанности:
    1. Предохранитель Пока-ёкэ (Заглушка Зрения): если к полю ввода прикреплена
       превью-миниатюра скриншота, роутер блокирует отправку картинки в Ollama
       и мгновенно возвращает безопасный вежливый отказ (модуль VL ещё не готов).
    2. Маршрутизация по глаголам действия в режиме «Помощник»: запрос
       перенаправляется модели mistral-small:22b, которая читает файл-справочник
       cad_reference.md и выдаёт вежливый инженерный ответ о «кубике на этапе
       сборки» с официальной справкой.
    3. Прочие запросы уходят в диалог с deepseek-r1:14b.

Ключевые принципы:
    - Никакого exec()/eval(). Роутер возвращает ЧИСТЫЙ словарь-решение, а механикой
      исполнения занимаются статичные классы (см. core_core.OllamaWorker).
    - Вызовы строго по иерархии: Диспетчер DeepSeek -> Валидатор Qwen -> Кубик Python.
    - Все ошибки и сообщения оформляются на русском языке (Канон 16.5).
"""

