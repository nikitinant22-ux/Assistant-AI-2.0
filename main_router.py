# ---------------------------------------------------------------------------
# Главный маршрутизатор (Канон 11.1)
# ---------------------------------------------------------------------------

def route_request(
    prompt: str,
    mode: str = MODE_ASSISTANT,
    has_screenshot: bool = False,
) -> dict:
    """Принимает запрос из UI и возвращает чистое решение-словарь для исполнения.

    Это ЕДИНАЯ точка входа всей логики ИИ-суждений. Функция ничего не исполняет
    сама — она лишь возвращает маршрут, который затем обработает движок стриминга.

    Аргументы:
        prompt: текст запроса пользователя.
        mode: текущий режим интерфейса ('chat' | 'assistant' | 'sandbox').
        has_screenshot: True, если к полю ввода прикреплено превью скриншота.

    Возвращает:
        dict — решение вида:
            {"action": "direct_reply", "reply": str, "thinking": str}  — мгновенный
                ответ без обращения к сети (заглушки).
            {"action": "chain", "orchestrator_model": str, "orchestrator_prompt": str,
             "assistant_model": str, "assistant_prompt": str, "user_prompt": str,
             "mode": str} — многомодельный конвейер режима «Чат».
            {"action": "stream", "model": str, "system_prompt": str,
             "user_prompt": str, "mode": str} — маршрут для потоковой генерации.
    """
    prompt = (prompt or "").strip()

    # 1. Предохранитель Пока-ёкэ (Заглушка Зрения). Картинка в Ollama НЕ уходит:
    #    мгновенно возвращаем безопасный отказ. Это исключает «ослепшее зрение»
    #    и неточные скриншоты конструкцией, а не инструкцией быть внимательным.
    if has_screenshot:
        return {
            "action": "direct_reply",
            "reply": VISION_REFUSAL_MESSAGE,
            "thinking": "",
            "title": "Заглушка зрения (VL отключён)",
        }

    # 2. Сквозная многомодельная оркестрация ВО ВСЕХ РЕЖИМАХ (Канон 16.5).
    #    Единая точка входа: ЛЮБОЙ запрос из бокса чата (Чат / Помощник /
    #    Песочница) сначала ВСЕГДА принимает Ведущий Архитектор-Градостроитель
    #    (deepseek-r1:14b). Его размышления на русском стримятся в спойлер
    #    «Размышления...», а итог рассуждений передаётся дальше нужной модели —
    #    Помощнику архитектора (mistral-small:22b), который формулирует финальный
    #    ответ на русском языке.
    #
    #    Гарантии передачи контекста (исполняет ChainedChatWorker из core_core):
    #      - буфер фазы Дипсика полностью собирает размышления и очищенное
    #        суждение, прежде чем передать их Помощнику;
    #      - сигнал thinking_changed транслирует мысли Дипсика в GUI на лету,
    #        плавно прорисовывая спойлер «Размышления...»;
    #      - после "done": true Дипсика фаза Мистрали бесшовно продолжает стрим
    #        в ТОТ ЖЕ текстовый лейбл чата — маркер окончания первой модели НЕ
    #        завершает общий QThread, т.к. обе фазы выполняются в одном run().
    if mode == MODE_ASSISTANT:
        # В режиме «Помощник» Мистраль отвечает как инженерный справочник,
        # читая cad_reference.md, но по-прежнему ПОСЛЕ размышлений Диспетчера.
        assistant_prompt = build_reference_system_prompt()
    else:
        assistant_prompt = CHAT_SYSTEM_PROMPT

    _mode_titles = {
        MODE_CHAT: "Чат",
        MODE_ASSISTANT: "Помощник",
        MODE_SANDBOX: "Песочница",
    }
    return {
        "action": "chain",
        "mode": mode,
        "title": (
            f"{_mode_titles.get(mode, mode)} → DeepSeek-R1 (Оркестратор) → "
            "Mistral-Small (Помощник)"
        ),
        "orchestrator_model": MODEL_DEEPSEEK,
        "orchestrator_prompt": CHAT_ORCHESTRATION_PROMPT,
        "assistant_model": MODEL_MISTRAL,
        "assistant_prompt": assistant_prompt,
        "user_prompt": prompt,
    }


